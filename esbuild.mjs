#!/usr/bin/env node
// Builds the extension and, for tests, each source module on its own.
//
//   node esbuild.mjs           dist/extension.js (CommonJS, `vscode` external)
//   node esbuild.mjs --tests   the same, plus out/test/<module>.mjs for every
//                              src/*.ts, so node --test can import the pure
//                              modules with a fake `vscode` object injected
//   node esbuild.mjs --server  rebuilds server/wisply-mcp.mjs from vendor/
//                              and src/editor-messages.mjs, and records its
//                              sha256 in vendor/SOURCE.json
//                              (scripts/sync-vendor.mjs does this after it
//                              vendors; test/bundle.test.mjs checks that a
//                              rebuild gives the same bytes)
//
// No source maps and no minification: the store reviewers and the user can
// read what runs.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

export const ROOT = dirname(fileURLToPath(import.meta.url));
export const SERVER_ENTRY = 'vendor/wisply-mcp/bin/wisply-mcp.mjs';
export const SERVER_BUNDLE = 'server/wisply-mcp.mjs';
export const TEST_OUT = 'out/test';
export const SOURCE_FILE = 'vendor/SOURCE.json';
/** The vendored connector's texts. */
export const VENDORED_MESSAGES = 'vendor/wisply-mcp/lib/messages.mjs';
/**
 * The connector's texts as this extension's bundle shows them. The vendored
 * modules import `./messages.mjs`; in the bundle that resolves to this file,
 * which re-exports the vendored texts and replaces the few that tell the user
 * (and the chat model) where the token comes from (see the file's header).
 */
export const EDITOR_MESSAGES = 'src/editor-messages.mjs';

/** The editor's Node: VS Code 1.93 ships Electron 30 with Node 20. */
const TARGET = 'node20';

/** @returns {import('esbuild').BuildOptions} */
export function extensionOptions() {
  return {
    absWorkingDir: ROOT,
    entryPoints: ['src/extension.ts'],
    outfile: 'dist/extension.js',
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: TARGET,
    external: ['vscode'],
    sourcemap: false,
    minify: false,
    legalComments: 'inline',
    charset: 'ascii',
    logLevel: 'warning',
  };
}

/** Every src/*.ts except declaration files, as out/test/<name>.mjs. */
export function testOptions() {
  const entryPoints = readdirSync(join(ROOT, 'src'))
    .filter((name) => name.endsWith('.ts') && !name.endsWith('.d.ts'))
    .sort()
    .map((name) => `src/${name}`);
  return {
    absWorkingDir: ROOT,
    entryPoints,
    outdir: TEST_OUT,
    outExtension: { '.js': '.mjs' },
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: TARGET,
    external: ['vscode'],
    sourcemap: false,
    charset: 'ascii',
    logLevel: 'warning',
  };
}

/**
 * Resolves the vendored modules' imports of lib/messages.mjs to
 * src/editor-messages.mjs. The overlay's own import of the vendored file
 * comes from src/, so it resolves as usual.
 * @returns {import('esbuild').Plugin}
 */
export function editorMessagesPlugin() {
  const vendored = join(ROOT, VENDORED_MESSAGES);
  const vendorDir = join(ROOT, 'vendor', 'wisply-mcp') + sep;
  return {
    name: 'wisply-editor-messages',
    setup(build) {
      build.onResolve({ filter: /(^|\/)messages\.mjs$/ }, (args) => {
        if (!args.importer.startsWith(vendorDir)) return undefined;
        if (resolve(args.resolveDir, args.path) !== vendored) return undefined;
        return { path: join(ROOT, EDITOR_MESSAGES) };
      });
    },
  };
}

/**
 * The vendored connector as one ES module that runs from any directory with
 * no sibling files, with the editor texts of src/editor-messages.mjs. The
 * banner names the source commit from vendor/SOURCE.json.
 * @param {{commit: string, repository: string}} source
 * @returns {import('esbuild').BuildOptions}
 */
export function serverBundleOptions({ commit, repository }) {
  return {
    absWorkingDir: ROOT,
    entryPoints: [SERVER_ENTRY],
    plugins: [editorMessagesPlugin()],
    outfile: SERVER_BUNDLE,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: TARGET,
    sourcemap: false,
    minify: false,
    legalComments: 'inline',
    charset: 'ascii',
    logLevel: 'warning',
    banner: {
      js: `// GENERATED by scripts/sync-vendor.mjs: the Wisply MCP connector (${repository} at ${commit}),\n` +
        `// bundled from vendor/wisply-mcp/ into one file, with the editor texts of ${EDITOR_MESSAGES}.\n` +
        '// Do not edit; re-vendor or rebuild instead (README).\n' +
        '// MIT License, Copyright (c) 2026 Alex Fallah (vendor/wisply-mcp/LICENSE).',
    },
  };
}

/** The wisply-mcp source recorded in vendor/SOURCE.json. */
export function vendoredMcpSource() {
  const source = JSON.parse(readFileSync(join(ROOT, SOURCE_FILE), 'utf8'));
  const mcp = source.sources.find((entry) => entry.repository === 'github:fal3/wisply-mcp');
  if (!mcp) throw new Error('vendor/SOURCE.json has no github:fal3/wisply-mcp source');
  return mcp;
}

/**
 * Builds the server bundle. With write: false the bytes come back instead.
 * @param {{write?: boolean, source?: {commit: string, repository: string}}} [options]
 * @returns {Promise<Uint8Array>}
 */
export async function buildServerBundle({ write = true, source = vendoredMcpSource() } = {}) {
  const result = await esbuild.build({ ...serverBundleOptions(source), write });
  if (write) return readFileSync(join(ROOT, SERVER_BUNDLE));
  return result.outputFiles[0].contents;
}

/** Rebuilds the bundle and records its sha256 (and the esbuild version) in vendor/SOURCE.json. */
async function rebuildServer() {
  const bytes = await buildServerBundle();
  const source = JSON.parse(readFileSync(join(ROOT, SOURCE_FILE), 'utf8'));
  source.bundle = {
    ...source.bundle,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    esbuild: esbuild.version,
  };
  writeFileSync(join(ROOT, SOURCE_FILE), `${JSON.stringify(source, null, 2)}\n`);
}

async function main(argv) {
  if (argv.includes('--server')) {
    await rebuildServer();
    return;
  }
  await esbuild.build(extensionOptions());
  if (argv.includes('--tests')) {
    rmSync(join(ROOT, TEST_OUT), { recursive: true, force: true });
    await esbuild.build(testOptions());
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main(process.argv.slice(2));
}
