#!/usr/bin/env node
// Rewrites the generated data modules from their JSON sources:
//
//   contract/mcp-contract.json -> contract/mcp-contract.mjs
//   clients/mcp-clients.json   -> clients/mcp-clients.mjs
//
// lib/ imports the .mjs files, not the JSON: a static import works on every
// Node 20 and survives a single-file bundle (the VS Code extension's), while
// the JSON files stay byte-identical to their sources for hashing. Non-ASCII
// characters are written as \u escapes, so the modules are plain ASCII.
//
//   node scripts/gen-data.mjs           write the modules
//   node scripts/gen-data.mjs --check   exit 1 if a module is out of date
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** [JSON source, generated module], relative to the repository root. */
export const DATA_FILES = Object.freeze([
  ['contract/mcp-contract.json', 'contract/mcp-contract.mjs'],
  ['clients/mcp-clients.json', 'clients/mcp-clients.mjs'],
]);

/**
 * The module text for one JSON source.
 * @param {string} jsonText the JSON file's contents
 * @param {string} source its path, for the header comment
 */
export function renderModule(jsonText, source) {
  const literal = JSON.stringify(JSON.parse(jsonText), null, 2)
    .replace(/[\u007f-￿]/g, (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`);
  return `// GENERATED by scripts/gen-data.mjs from ${source}. Do not edit: change the JSON\n` +
    '// and run `npm run gen-data`. tests/data.test.mjs checks that the two agree.\n' +
    `export default ${literal};\n`;
}

/**
 * Writes (or, with check, compares) every module whose JSON source exists.
 * @param {{root?: string, check?: boolean}} [options]
 * @returns {string[]} the modules that were out of date
 */
export function generate({ root = ROOT, check = false } = {}) {
  const stale = [];
  for (const [source, target] of DATA_FILES) {
    const sourcePath = join(root, source);
    if (!existsSync(sourcePath)) continue;
    const text = renderModule(readFileSync(sourcePath, 'utf8'), source);
    const targetPath = join(root, target);
    const current = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : null;
    if (current === text) continue;
    stale.push(target);
    if (!check) writeFileSync(targetPath, text);
  }
  return stale;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const stale = generate({ check });
  if (check && stale.length > 0) {
    process.stderr.write(`Out of date (run npm run gen-data): ${stale.join(', ')}\n`);
    process.exit(1);
  }
  for (const target of check ? [] : stale) process.stdout.write(`wrote ${target}\n`);
}
